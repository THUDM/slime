def _ppo_advantages(compute_advantages_and_returns, log_probs, loss_mask):
    rollout_data = {
        "log_probs": [log_probs],
        "ref_log_probs": [torch.zeros_like(log_probs)],
        "rewards": [1.0],
        "values": [torch.zeros_like(log_probs)],
        "response_lengths": [len(log_probs)],
        "total_lengths": [len(log_probs) + 3],
        "loss_masks": [loss_mask],
    }
    args = Namespace(
        advantage_estimator="ppo",
        kl_coef=0.05,
        kl_loss_type="k1",
        use_rollout_logprobs=False,
        custom_advantage_function_path=None,
        normalize_advantages=False,
        use_opd=False,
        gamma=1.0,
        lambd=1.0,
    )
    compute_advantages_and_returns(args, rollout_data)
    return rollout_data["advantages"][0]


def test_ppo_reward_kl_ignores_loss_masked_tokens(compute_advantages_and_returns):
    """Env/tool tokens (loss_mask=0) are not generated by the policy, so their KL
    must not enter the token-level reward that GAE propagates to policy tokens."""
    loss_mask = torch.tensor([1.0, 1.0, 0.0, 0.0, 1.0])
    kl_on_masked_tokens_only = torch.tensor([0.0, 0.0, 5.0, 5.0, 0.0])

    advantages = _ppo_advantages(compute_advantages_and_returns, kl_on_masked_tokens_only, loss_mask)
    no_kl_advantages = _ppo_advantages(compute_advantages_and_returns, torch.zeros(5), loss_mask)

    torch.testing.assert_close(advantages, no_kl_advantages)


def test_ppo_reward_kl_still_penalizes_policy_tokens(compute_advantages_and_returns):
    loss_mask = torch.tensor([1.0, 1.0, 0.0, 0.0, 1.0])
    log_probs = torch.tensor([0.0, 2.0, 0.0, 0.0, 0.0])

    advantages = _ppo_advantages(compute_advantages_and_returns, log_probs, loss_mask)

    # gamma = lambd = 1 and values = 0, so advantage_t = reward - kl_coef * (KL at or after t).
    torch.testing.assert_close(advantages, torch.tensor([0.9, 0.9, 1.0, 1.0, 1.0]))


